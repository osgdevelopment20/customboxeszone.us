<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Service account credentials
    |--------------------------------------------------------------------------
    |
    | The Indexing API only accepts service account (JWT) authentication. Create
    | a service account in Google Cloud, enable the "Indexing API", download the
    | JSON key and add the service account e-mail as an *owner* of the property
    | in Google Search Console.
    |
    | The key can either live on disk (uploaded through the dashboard) or be
    | supplied through the environment as raw / base64 encoded JSON.
    |
    */

    'credentials_path' => env('GOOGLE_INDEXING_CREDENTIALS') ?: storage_path('app/google/indexing-service-account.json'),

    'credentials_json' => env('GOOGLE_INDEXING_CREDENTIALS_JSON'),

    /*
    |--------------------------------------------------------------------------
    | Limits
    |--------------------------------------------------------------------------
    |
    | Google's default publish quota is 200 URLs per project per day and a
    | single batch request may hold a maximum of 100 calls. "resubmit_after_days"
    | stops the same URL from burning quota over and over again.
    |
    */

    'daily_quota' => (int) env('GOOGLE_INDEXING_DAILY_QUOTA', 200),

    'batch_size' => (int) env('GOOGLE_INDEXING_BATCH_SIZE', 100),

    'resubmit_after_days' => (int) env('GOOGLE_INDEXING_RESUBMIT_AFTER_DAYS', 7),

    'timeout' => (int) env('GOOGLE_INDEXING_TIMEOUT', 60),

    // Send one multipart/mixed batch per 100 URLs instead of one request per URL.
    'use_batch' => (bool) env('GOOGLE_INDEXING_USE_BATCH', true),

    // Only accept URLs that belong to these hosts. Empty = allow everything.
    'allowed_hosts' => array_values(array_filter(array_map('trim', explode(
        ',',
        (string) env('GOOGLE_INDEXING_ALLOWED_HOSTS', parse_url((string) env('APP_URL'), PHP_URL_HOST) ?: '')
    )))),

    /*
    |--------------------------------------------------------------------------
    | URL sources
    |--------------------------------------------------------------------------
    */

    'sources' => [

        'sitemap' => [
            // Local sitemap files generated by the application.
            'files' => [
                public_path('mysitemap.xml'),
            ],
            // Remote sitemaps (sitemap index files are followed automatically).
            'urls' => array_values(array_filter(array_map('trim', explode(
                ',',
                (string) env('GOOGLE_INDEXING_SITEMAP_URLS', '')
            )))),
        ],

        'database' => [
            // Static pages submitted alongside the models below.
            'routes' => [
                'index', 'aboutUs', 'contactUs', 'allproducts', 'allcategories',
                'blog.page', 'faq', 'termsAndCondition', 'SecurityAndPrivacy', 'refundPolicy',
            ],
            // model => [route name, slug column]
            'models' => [
                \App\Models\Product::class  => ['route' => 'page', 'slug' => 'slug'],
                \App\Models\Category::class => ['route' => 'page', 'slug' => 'slug'],
                \App\Models\Blog::class     => ['route' => 'blog.detail', 'slug' => 'slug'],
            ],
        ],
    ],

    /*
    |--------------------------------------------------------------------------
    | Scheduled submission
    |--------------------------------------------------------------------------
    |
    | When enabled the scheduler pushes recently changed URLs to Google once a
    | day. Requires the Laravel scheduler cron entry to be present.
    |
    */

    'schedule' => [
        'enabled' => (bool) env('GOOGLE_INDEXING_SCHEDULE', false),
        'time'    => env('GOOGLE_INDEXING_SCHEDULE_TIME') ?: '03:00',
        'source'  => env('GOOGLE_INDEXING_SCHEDULE_SOURCE') ?: 'database',
        'since'   => (int) env('GOOGLE_INDEXING_SCHEDULE_SINCE_DAYS', 2),
        'limit'   => (int) env('GOOGLE_INDEXING_SCHEDULE_LIMIT', 200),
    ],
];
